"""Check that every PRD requirement has a home in a spec. Standard library only.

Usage: python3 docs/roadmap/check_traceability.py [--write]
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPECS = ROOT / "specs"
OUTPUT = ROOT / "docs/roadmap/traceability.md"
TOKEN = re.compile(r"\b(?:FR|UX|AT)-\d{2}\b|\bS\d{2}\b|\bP\d{2}\b")
FIELD = re.compile(r"^\*\*(Covers|Depends on)\*\*: (.*)$", re.MULTILINE)
GROUPS = {
    "Functional requirements": [f"FR-{n:02}" for n in range(1, 23)],
    "UX checks": [f"UX-{n:02}" for n in range(1, 21)],
    "Acceptance tests": [f"AT-{n:02}" for n in range(1, 59)],
    "Screens": [f"S{n:02}" for n in range(1, 13)],
    "Journeys": [f"P{n:02}" for n in range(1, 12)],
}


def load_specs() -> tuple[dict[str, list[str]], list[str]]:
    """Read every spec header.

    Returns:
        tuple[dict[str, list[str]], list[str]]: Requirement to spec folders, and any structural problems.
    """
    homes: dict[str, list[str]] = {}
    problems = []
    folders = sorted(path for path in SPECS.iterdir() if path.is_dir())
    numbers = {path.name[:3] for path in folders}
    for folder in folders:
        for required in ("spec.md", "plan.md"):
            if not (folder / required).is_file():
                problems.append(f"{folder.name}: missing {required}")
        spec = folder / "spec.md"
        if not spec.is_file():
            continue
        fields = dict(FIELD.findall(spec.read_text(encoding="utf-8")))
        if "Covers" not in fields or "Depends on" not in fields:
            problems.append(f"{folder.name}: missing Covers or Depends on")
            continue
        for token in TOKEN.findall(fields["Covers"]):
            homes.setdefault(token, []).append(folder.name)
        for dependency in re.findall(r"\b\d{3}\b", fields["Depends on"]):
            if dependency not in numbers:
                problems.append(f"{folder.name}: depends on missing {dependency}")
            elif dependency >= folder.name[:3]:
                problems.append(f"{folder.name}: depends on later spec {dependency}")
    return homes, problems


def render(homes: dict[str, list[str]]) -> str:
    """Render the traceability table."""
    lines = [
        "# Traceability",
        "",
        "Generated by `check_traceability.py` from each spec's **Covers** line. Do not edit.",
        "",
    ]
    for title, ids in GROUPS.items():
        lines += [f"## {title}", "", "| ID | Specs |", "|---|---|"]
        lines += [f"| {item} | {', '.join(f'`{home}`' for home in homes.get(item, []))} |" for item in ids]
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    """Report gaps, and rewrite the table when asked."""
    homes, problems = load_specs()
    problems += [f"{item}: no spec covers it" for ids in GROUPS.values() for item in ids if item not in homes]
    if "--write" in sys.argv:
        OUTPUT.write_text(render(homes), encoding="utf-8")
    elif OUTPUT.is_file() and OUTPUT.read_text(encoding="utf-8") != render(homes):
        problems.append("traceability.md is stale: run with --write")
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    print(f"{len(homes)} requirements mapped across {sum(path.is_dir() for path in SPECS.iterdir())} specs.")


if __name__ == "__main__":
    main()
