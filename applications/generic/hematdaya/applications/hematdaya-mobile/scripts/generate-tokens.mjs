// Generates src/design/tokens.generated.ts from design/tokens.json, the copied HematDaya Design System tokens.
// Only semantic tokens are exposed: components never read palette values. Run with `make tokens`.
import { readFileSync, writeFileSync } from 'node:fs';

const source = JSON.parse(readFileSync(new URL('../design/tokens.json', import.meta.url)));
const REM = 16;

const camel = (name) => name.replace(/-(\w)/g, (_, letter) => letter.toUpperCase());
const pixels = (value) => Number.parseFloat(value);
const rem = (value) => Number.parseFloat(value) * REM;

const byName = new Map(source.color.tokens.map((token) => [token.name, token.value]));
const resolve = (value) => {
  const alias = /^\{(.+)\}$/.exec(value);
  return alias ? resolve(byName.get(alias[1])) : value;
};

function group(tokens, prefix, convert) {
  return Object.fromEntries(
    tokens
      .filter((token) => token.name.startsWith(prefix))
      .map((token) => [camel(token.name.slice(prefix.length)), convert(token.value)]),
  );
}

const componentPrefixes = ['button-', 'field-', 'tab-'];
const components = source.color.tokens.filter((token) => componentPrefixes.some((p) => token.name.startsWith(p)));

const tokens = {
  color: group(source.color.tokens, 'color-', resolve),
  component: group(components, '', resolve),
  space: group(source.spacing.tokens, 'space-', pixels),
  radius: group(source.radius.tokens, 'radius-', pixels),
  size: group(source.size.tokens, 'size-', pixels),
  duration: group(source.duration.tokens, 'duration-', pixels),
  type: Object.fromEntries(
    source.type.groups
      .flatMap((entry) => entry.styles)
      .map((style) => [
        camel(style.name.replace('type-', '')),
        { fontSize: rem(style.fontSize), lineHeight: rem(style.lineHeight), fontWeight: String(style.fontWeight) },
      ]),
  ),
};

const banner = '// Generated by scripts/generate-tokens.mjs from design/tokens.json. Do not edit.\n';
writeFileSync(
  new URL('../src/design/tokens.generated.ts', import.meta.url),
  `${banner}export const tokens = ${JSON.stringify(tokens, null, 2)} as const;\n`,
);
